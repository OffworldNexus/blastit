/**
 * Expensive-tier budget guard.
 *
 * - Sums the cost of every session in this project executed by an expensive-tier agent
 *   (strategist, architect, expert) or expensive model (Gemini 4 Carbon / Argon / Opus).
 * - Writes plan/BUDGET.md (generated) from the cap in plan/BUDGET.json (owner-edited).
 * - Denies launching expensive subagents once spend >= cap, telling the agent to open a
 *   HUMAN.md request instead and continue with cheap work.
 */
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

export const EXPENSIVE_AGENTS = new Set(["strategist", "architect", "expert"]);
const EXPENSIVE_MODEL_RE = /opus|gemini-4-carbon|gemini-4-argon/i;
const STORAGE_PREFIX = "expensive-cost/";

interface BudgetConfig {
  expensive_cap_usd: number;
  opus_cap_usd?: number;
  warn_ratio: number;
}

interface SessionLike {
  id?: string;
  agent?: string;
  cost?: number;
  model?: { id?: string; providerID?: string };
  location?: { directory?: string };
}

export interface BudgetCtx {
  storage: {
    get(key: string): Promise<unknown>;
    set(key: string, value: never): Promise<void>;
    scan(o: { prefix: string; after?: string; limit?: number }): Promise<{
      entries: readonly { key: string; value: unknown }[];
      next?: string;
    }>;
  };
  session: {
    get(i: { sessionID: never }): Promise<unknown>;
    list(i: Record<string, unknown>): Promise<unknown>;
  };
}

export class ExpensiveBudget {
  private lastWrite = 0;

  constructor(
    private readonly ctx: BudgetCtx,
    private readonly root: string,
    private readonly projectID: string | undefined,
  ) {}

  get planDir(): string {
    return join(this.root, "plan");
  }

  async config(): Promise<{ cap: number; warnRatio: number }> {
    try {
      const raw = JSON.parse(await readFile(join(this.planDir, "BUDGET.json"), "utf8")) as Partial<BudgetConfig>;
      const cap = Number(raw.expensive_cap_usd ?? raw.opus_cap_usd ?? 100);
      return { cap, warnRatio: Number(raw.warn_ratio ?? 0.8) };
    } catch {
      return { cap: 100, warnRatio: 0.8 };
    }
  }

  private isExpensive(s: SessionLike): boolean {
    if (s.agent && EXPENSIVE_AGENTS.has(s.agent)) return true;
    return EXPENSIVE_MODEL_RE.test(String(s.model?.id ?? ""));
  }

  private inProject(s: SessionLike): boolean {
    const dir = s.location?.directory;
    return !dir || String(dir).startsWith(this.root);
  }

  async record(s: SessionLike): Promise<void> {
    if (!s.id || !this.isExpensive(s) || !this.inProject(s)) return;
    const cost = Number(s.cost ?? 0);
    const prev = Number((await this.ctx.storage.get(STORAGE_PREFIX + s.id)) ?? 0);
    if (cost > prev) await this.ctx.storage.set(STORAGE_PREFIX + s.id, cost as never);
  }

  async recordSession(sessionID: string): Promise<void> {
    const info = (await this.ctx.session.get({ sessionID: sessionID as never })) as SessionLike;
    await this.record({ ...info, id: info.id ?? sessionID });
  }

  async backfill(): Promise<void> {
    let cursor: unknown = undefined;
    for (let page = 0; page < 50; page++) {
      const res = (await this.ctx.session.list(
        cursor ? { cursor, limit: 100 } : { project: this.projectID, limit: 100 },
      )) as { data?: SessionLike[]; cursor?: { next?: unknown } };
      for (const s of res.data ?? []) await this.record(s);
      cursor = res.cursor?.next;
      if (!cursor) break;
    }
  }

  async total(): Promise<number> {
    let sum = 0;
    let after: string | undefined;
    for (;;) {
      const page = await this.ctx.storage.scan({ prefix: STORAGE_PREFIX, after, limit: 500 });
      for (const e of page.entries) sum += Number(e.value ?? 0);
      if (!page.next) break;
      after = page.next;
    }
    return sum;
  }

  async refreshReport(force = false): Promise<void> {
    const now = Date.now();
    if (!force && now - this.lastWrite < 20_000) return;
    this.lastWrite = now;
    const cfg = await this.config();
    const spent = await this.total();
    const ratio = cfg.cap > 0 ? spent / cfg.cap : 1;
    const status = ratio >= 1 ? "EXHAUSTED" : ratio >= cfg.warnRatio ? "WARNING" : "OK";
    const text = [
      "# Expensive-tier budget (generated by the autopilot plugin, do not edit; edit plan/BUDGET.json)",
      "",
      `- status: ${status}`,
      `- expensive spent: $${spent.toFixed(2)} of $${cfg.cap.toFixed(2)} cap (${(ratio * 100).toFixed(0)}%)`,
      `- updated: ${new Date().toISOString()}`,
      "",
      status === "EXHAUSTED"
        ? "Expensive-tier agents (strategist, architect, expert) are blocked. Open a HUMAN.md request asking the owner to raise `expensive_cap_usd` in plan/BUDGET.json, and keep doing cheap work."
        : status === "WARNING"
          ? "Over the warning threshold: escalate only when indispensable; prefer cheap retries and researchers."
          : "Within budget.",
      "",
    ].join("\n");
    await writeFile(join(this.planDir, "BUDGET.md"), text, "utf8");
  }

  async denyMessage(agent: string): Promise<string | undefined> {
    const cfg = await this.config();
    const spent = await this.total();
    if (spent < cfg.cap) return undefined;
    return (
      `Expensive-tier budget exhausted: $${spent.toFixed(2)} spent of $${cfg.cap} cap, so '${agent}' cannot be launched. ` +
      `Do NOT retry. Run: uv run --no-project tools/plan.py --agent <you> human add "Expensive budget exhausted ($${spent.toFixed(2)}/$${cfg.cap}). ` +
      `Please raise expensive_cap_usd in plan/BUDGET.json to continue escalations." ` +
      `Then mark the node blocked (if it needs the expensive tier) and continue with other cheap work.`
    );
  }
}
