//! Records the CPython minor this shim is built for, and the CPython table the
//! crate publishes, both derived from `packaging/languages.tsv` (`MB.67.3`).
//!
//! `blastit_py_minor()` must report the minor of the interpreter `make py-sapi`
//! built against (`PYO3_PYTHON`), never a literal in the source: the same crate
//! produces one `libblastit_<slug>-*.so` per declared CPython, and a literal
//! would make one of them lie about the vtable it exports. The value is read from
//! the interpreter itself, which is the same one pyo3's own build script
//! validated, and written into the crate both as `BLASTIT_PY_MINOR` and as the
//! numeric `BUILT_PY_MINOR` the artifact's compile-time check reads.
//!
//! **Strictness is the artifact's, not every build shape's.** `make py-sapi`
//! builds with the `extension-module` feature and an explicit `PYO3_PYTHON`;
//! that build refuses, by name, a CPython the TSV does not declare. Any other
//! build (a plain `cargo test` on a host whose `python3` is old) only warns and
//! continues, so the crate stays testable everywhere while the shipped artifact
//! is checked. `SUPPORTED_PY_MINORS`, `supports_py_minor` and `BUILT_PY_MINOR`
//! are generated into `$OUT_DIR/languages.rs`, which `src/lib.rs` `include!`s.

include!("../../packaging/languages.rs.inc");

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

fn main() {
    let root = workspace_root();
    let tsv = root.join("packaging/languages.tsv");
    let inc = root.join("packaging/languages.rs.inc");
    println!("cargo:rerun-if-changed={}", absolute(&tsv));
    println!("cargo:rerun-if-changed={}", absolute(&inc));
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=PYO3_PYTHON");

    let rows = load(&tsv).unwrap_or_else(|err| panic!("blastit-py-shim: {err}"));
    let python = rows_of(&rows, "python");
    if python.is_empty() {
        panic!(
            "blastit-py-shim: {} declares no python row, so no shim can be built",
            tsv.display()
        );
    }
    let artifact = std::env::var_os("CARGO_FEATURE_EXTENSION_MODULE").is_some()
        && std::env::var_os("PYO3_PYTHON").is_some();
    let minor = built_minor(&python, artifact);

    let out_dir =
        std::env::var("OUT_DIR").unwrap_or_else(|_| panic!("blastit-py-shim: cargo sets OUT_DIR"));
    let path = Path::new(&out_dir).join("languages.rs");
    std::fs::write(&path, emit(&python, minor, artifact))
        .unwrap_or_else(|err| panic!("blastit-py-shim: cannot write {}: {err}", path.display()));
    println!("cargo:rustc-env=BLASTIT_PY_MINOR={minor}");

    if std::env::var_os("CARGO_FEATURE_EXTENSION_MODULE").is_some() {
        // An `extension-module` link target has no `libpython` to resolve `Py*`
        // against (that is the point of the feature), so the `cdylib` is linked
        // with those references left unresolved on purpose — `nm -uD` must show
        // them. A *test* build in this configuration compiles the
        // interpreter-backed half out (see `src/lib.rs`), so this only ever
        // applies to the artifact.
        println!("cargo:rustc-link-arg=-Wl,--unresolved-symbols=ignore-all");
    }
}

/// The repository root, two directories above this crate.
fn workspace_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .ancestors()
        .nth(2)
        .map(Path::to_path_buf)
        .unwrap_or_else(|| panic!("blastit-py-shim: build.rs has no workspace root"))
}

/// The absolute spelling of `path`, for `cargo:rerun-if-changed`.
fn absolute(path: &Path) -> String {
    std::fs::canonicalize(path).map_or_else(
        |_| path.display().to_string(),
        |resolved| resolved.display().to_string(),
    )
}

/// The generated `$OUT_DIR/languages.rs`, included by `src/lib.rs`.
fn emit(python: &[&Row], minor: u32, artifact: bool) -> String {
    let mut out = String::new();
    out.push_str("// @generated by build.rs from packaging/languages.tsv. Do not edit.\n\n");

    out.push_str("/// The CPython minors this build ships a shim for, newest first.\n");
    let _ = writeln!(
        out,
        "pub const SUPPORTED_PY_MINORS: [u32; {}] = [{}];\n",
        python.len(),
        python
            .iter()
            .map(|row| encoded(&row.version).to_string())
            .collect::<Vec<String>>()
            .join(", ")
    );

    out.push_str("/// Whether `minor` is one of the CPython minors `packaging/languages.tsv`\n/// declares.\n");
    let _ = writeln!(
        out,
        "pub const fn supports_py_minor(minor: u32) -> bool {{\n    matches!(minor, {})\n}}\n",
        python
            .iter()
            .map(|row| encoded(&row.version).to_string())
            .collect::<Vec<String>>()
            .join(" | ")
    );

    out.push_str("/// The CPython minor this shim was built for (`PYO3_PYTHON`).\n// Emitted only in the shapes that compile its reader (`surface`), so a\n// `test` + `extension-module` build has no dead constant.\n#[cfg(not(all(test, feature = \"extension-module\")))]\n");
    let _ = writeln!(out, "const BUILT_PY_MINOR: u32 = {minor};\n");

    if artifact {
        out.push_str("// The shipped artifact's own reported minor must be a declared one: a\n// shim no boot can select is a build error, not a runtime surprise. Only the\n// `make py-sapi` shape (`extension-module` + `PYO3_PYTHON`) is held to it, so a\n// plain `cargo test` on a host with an older `python3` still builds.\n#[cfg(not(all(test, feature = \"extension-module\")))]\nconst _: () = assert!(supports_py_minor(BUILT_PY_MINOR));\n");
    }

    out
}

/// The minor `PYO3_PYTHON` reports (`313`), refusing one the TSV does not declare
/// when this is the shipped artifact.
fn built_minor(python: &[&Row], artifact: bool) -> u32 {
    let interpreter = std::env::var_os("PYO3_PYTHON").unwrap_or_else(|| "python3".into());
    let output = Command::new(&interpreter)
        .args([
            "-c",
            "import sys; print(sys.version_info[0] * 100 + sys.version_info[1])",
        ])
        .output()
        .unwrap_or_else(|err| {
            panic!(
                "blastit-py-shim: cannot run PYO3_PYTHON ({}): {err}; set PYO3_PYTHON to the \
                 CPython this shim is built for",
                interpreter.to_string_lossy()
            )
        });
    if !output.status.success() {
        panic!(
            "blastit-py-shim: PYO3_PYTHON ({}) did not answer `sys.version_info`; set PYO3_PYTHON \
             to the CPython this shim is built for",
            interpreter.to_string_lossy()
        );
    }
    let text = String::from_utf8_lossy(&output.stdout).trim().to_owned();
    let Ok(minor) = text.parse::<u32>() else {
        panic!(
            "blastit-py-shim: PYO3_PYTHON ({}) answered {text:?}, not a minor encoding",
            interpreter.to_string_lossy()
        );
    };
    let declared: Vec<u32> = python.iter().map(|row| encoded(&row.version)).collect();
    if declared.contains(&minor) {
        return minor;
    }
    let versions: Vec<&str> = python.iter().map(|row| row.version.as_str()).collect();
    let sentence = sentence("CPython", &ascending(&versions));
    if artifact {
        panic!(
            "blastit-py-shim: PYO3_PYTHON ({}) is CPython {minor}, and packaging/languages.tsv \
             declares only {sentence}; set PYO3_PYTHON to one of the declared interpreters",
            interpreter.to_string_lossy()
        );
    }
    println!(
        "cargo:warning=blastit-py-shim: PYO3_PYTHON ({}) is CPython {minor}, which \
         packaging/languages.tsv does not declare ({sentence}); this is not the shipped artifact, \
         so the build continues, but a shim built for it could never be selected",
        interpreter.to_string_lossy()
    );
    minor
}

/// `"3.13"` as the `py_minor` encoding (`313`).
fn encoded(version: &str) -> u32 {
    let (major, minor) = version
        .split_once('.')
        .unwrap_or_else(|| panic!("packaging/languages.rs.inc parsed a version without a dot"));
    let major: u32 = major
        .parse()
        .unwrap_or_else(|_| panic!("packaging/languages.rs.inc parsed a non-numeric major"));
    let minor: u32 = minor
        .parse()
        .unwrap_or_else(|_| panic!("packaging/languages.rs.inc parsed a non-numeric minor"));
    major * 100 + minor
}
